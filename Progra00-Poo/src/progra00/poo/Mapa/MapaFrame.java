        int j = Integer.parseInt(txtJ.getText());
        
        if(i < 0 || 25 < i){
            lblWarningI.setText("La defensa debe de ir dentro del tablero");
        }
        if(j < 0 || 25 < j){
            lblWarningJ.setText("La defensa debe ir dentro del tablero");
        }
        
        this.addDefensa(i, j);
        
        
